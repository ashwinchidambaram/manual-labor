"""README.md of the export: what it is, how IDs work, how to ingest (design 11 section 5.2)."""

from __future__ import annotations

from manuallabor.contracts.io import to_jsonable
from manuallabor.contracts.manifest import Manifest

__all__ = ["render_readme"]

FIG_REGEX = r"FIG-[a-z0-9-]+-p\d{3}-\d{2}"
FIG_LINE_REGEX = (
    r"`^!\[FIG-[a-z0-9-]+-p\d{3}-\d{2} " + "\u2014" + r" .*\]"
    r"\(images/[a-z0-9-]+/FIG-[a-z0-9-]+-p\d{3}-\d{2}\.png\)$`"
)


def render_readme(m: Manifest) -> str:
    """Deterministic: the only time in it is `manifest.project.generated_at`."""
    gen = str(to_jsonable(m.project)["generated_at"])
    pages = len({(a.source_doc, p) for a in m.articles for p in a.pages})
    lines: list[str] = [
        f"# {m.project.name}: knowledge base export",
        "",
        "## What this is",
        "",
        f"Generated by Manual Labor {m.project.tool_version} at {gen}.",
        f"This archive holds {len(m.articles)} articles, {len(m.figures)} figures and "
        f"{pages} source pages from {len(m.docs)} source document(s).",
        "Article text is the source text, cleaned (hyphenation, line wraps, bullet glyphs); "
        "it is never rewritten, summarised or embellished.",
        "",
        "Source documents:",
        "",
    ]
    for d in m.docs:
        lines.append(f"- `{d.slug}`: {d.filename} (sha256 {d.sha256[:12]})")
    lines += [
        "",
        "## Contents",
        "",
        "```",
        "articles/<article-id>.md        one Markdown file per article, YAML frontmatter first",
        "images/<doc-slug>/FIG-*.png     figure images (vector figures also ship FIG-*.svg)",
        "images/<doc-slug>/FIG-*.json    one sidecar record per figure",
        "manifest.json                   projects, documents, articles, figures, review stats,",
        "                                models and threshold used, overrides, block accounting",
        "README.md                       this file",
        "```",
        "",
        "## IDs",
        "",
        "- Document: `<doc-slug>`, lowercase, from the filename or title.",
        "- Block: `b-<doc-slug>-p<page:03d>-<n:02d>`; every parsed block appears in "
        "`manifest.json` under `accounting`, either in one article or as `unassigned` with a "
        "reason.",
        f"- Figure: `FIG-<doc-slug>-p<page:03d>-<n:02d>`, matched by the regex `{FIG_REGEX}`.",
        "- Article: `<doc-slug>--<topic-slug>`, or `<doc-slug>` for one article per document.",
        "- Figure references in articles are single lines: "
        "`![FIG-ID — caption](images/<doc-slug>/FIG-ID.png)`. The alt text starts with the "
        "figure ID, then ` — `, then the original caption (or the generated description, "
        "prefixed `[generated]`, when the source has no caption).",
        "- A figure reference line matches the regex " + FIG_LINE_REGEX + ".",
        "- Every figure reference resolves to an image file and to a `.json` sidecar in the same "
        "folder. The same diagram found in several documents is stored once; the other "
        "figures point at it and record `duplicate_of` in `manifest.json`.",
        "",
        "## How to ingest",
        "",
        "1. Read `articles/*.md` (glob). Split each file on the first two `---` lines: the YAML "
        "frontmatter, then the Markdown body.",
        "2. Frontmatter keys: `id, title, source_doc, source_file, product_model, pages, "
        "sections, figures, blocks, review, generated_at`.",
        "3. `manifest.json` maps article id to file to source blocks and figures.",
        "4. For text-only retrieval use a figure sidecar's `caption_original` and, when you "
        "need more, `description_generated` (always machine generated, never source text).",
        "5. The body is source text; Markdown meta-characters in it are not escaped.",
        "",
        "## Faithfulness",
        "",
        "Cleanup may only join hyphenated line breaks, normalise whitespace and bullet glyphs "
        "and strip header/footer text. Numbers are checked against the source. "
        f"`review` in each article counts the approved blocks, the human-edited blocks and "
        f"the overrides. {len(m.review_stats.numbers_verified_blocks)} block(s) with numeric "
        "specifications were verified by a human (`review_stats.numbers_verified_blocks`).",
        "",
        "## Overrides",
        "",
    ]
    if m.overrides:
        lines.append(
            f"{len(m.overrides)} block(s) were exported without human approval; "
            "see `overrides` in `manifest.json` for each block and the reason."
        )
    else:
        lines.append("None: every exported block was auto-approved or approved by a human.")
    lines += ["", "## Models and threshold used", ""]
    lines.append(f"Review threshold: {m.threshold}. Article split: {m.article_split.value}.")
    for task in sorted(m.models, key=lambda t: t.value):
        ref = m.models[task]
        lines.append(f"- {task.value}: {ref.provider}/{ref.model}")
    lines += ["", "## Learning provenance", ""]
    if not m.learning.docs:
        lines.append("No learning snapshot was recorded.")
    else:
        lines.append(f"Learning enabled: {'yes' if m.learning.enabled else 'no'}.")
        for slug in sorted(m.learning.docs):
            e = m.learning.docs[slug]
            lines.append(f"- `{slug}`: grouping `{e.group}`, cleanup `{e.clean}`")
    return "\n".join(lines) + "\n"
